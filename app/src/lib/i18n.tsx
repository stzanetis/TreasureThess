const strings: Record<Lang, Record<StringKey, string>> = { en, el };

export type T = (key: StringKey, vars?: Record<string, string | number>) => string;

const deviceLang: Lang = Intl.DateTimeFormat().resolvedOptions().locale.startsWith('el') ? 'el' : 'en';

const LanguageContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void }>({ lang: deviceLang, setLang: () => {} });

/** Holds the chosen language: the phone's language at first, then whatever the user picks in Settings. */
export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(deviceLang);

  useEffect(() => {
    AsyncStorage.getItem('lang').then((saved) => {
      if (saved === 'en' || saved === 'el') setLangState(saved);
    });
  }, []);

  const setLang = (next: Lang) => {
    setLangState(next);
    AsyncStorage.setItem('lang', next);
  };

  return <LanguageContext.Provider value={{ lang, setLang }}>{children}</LanguageContext.Provider>;
}

export const useLanguage = () => useContext(LanguageContext);

/** Returns t('key', { n: 3 }): the string in the current language with {n} filled in. */
export function useT(): T {
  const { lang } = useLanguage();
  return (key, vars) => strings[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? ''));
}
